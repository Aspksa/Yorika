"""Tools Yorika's own model can call by writing [[calc: …]], [[time:]], [[memory: …]] or [[skill: …]] in an answer.

The model only learns to write the call; the result is computed here, so arithmetic and the
clock are exact instead of guessed. Lessons are generated by code and shown before they are
added, so the owner approves them as a pack.
"""
import ast
import operator
import random
import re
from datetime import datetime

CALL = re.compile(r"\[\[(calc|time|memory|skill):([^\]]{0,200})\]\]")
OPS = {ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul, ast.Div: operator.truediv,
       ast.Pow: operator.pow, ast.Mod: operator.mod, ast.FloorDiv: operator.floordiv,
       ast.USub: operator.neg, ast.UAdd: operator.pos}
WEEKDAYS = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]


def calc(expression):
    """Arithmetic only: numbers, + - * / // % ** and brackets, with bounded powers."""
    text = expression.replace("×", "*").replace("÷", "/").replace(",", ".").replace("^", "**").strip()
    if not text or len(text) > 120:
        raise ValueError("Пустое или слишком длинное выражение")

    def walk(node):
        if isinstance(node, ast.Expression):
            return walk(node.body)
        if isinstance(node, ast.Constant) and type(node.value) in (int, float):
            return node.value
        if isinstance(node, ast.UnaryOp) and type(node.op) in OPS:
            return OPS[type(node.op)](walk(node.operand))
        if isinstance(node, ast.BinOp) and type(node.op) in OPS:
            left, right = walk(node.left), walk(node.right)
            if isinstance(node.op, ast.Pow) and (abs(right) > 12 or abs(left) > 10 ** 6):
                raise ValueError("Слишком большая степень")
            return OPS[type(node.op)](left, right)
        raise ValueError("Можно только числа и + - * / ( )")
    try:
        value = walk(ast.parse(text, mode="eval"))
    except (SyntaxError, ZeroDivisionError, OverflowError):
        raise ValueError("Не получилось посчитать") from None
    if isinstance(value, float):
        value = round(value, 6)
        if value.is_integer():
            value = int(value)
    return str(value).replace(".", ",")


def now_text(moment=None):
    moment = moment or datetime.now()
    return "%s, %02d:%02d, %s" % (moment.strftime("%d.%m.%Y"), moment.hour, moment.minute, WEEKDAYS[moment.weekday()])


def memory(query, directory=None):
    from backend.storage import Store
    if not query.strip():
        return "запрос пустой"
    with Store(directory) as db:
        try:
            rows = db.search_memory_index(query, 1)
        except RuntimeError:
            rows = db.search_records("memories", query, 1)
    text = rows[0]["value"].get("text") if rows else None
    return text[:300] if isinstance(text, str) else "в памяти ничего нет"


def run_tools(answer, directory=None, moment=None):
    """Replaces every tool call in an answer with its result; returns (text, calls made)."""
    calls = []

    def replace(match):
        name, argument = match.group(1), match.group(2).strip()
        try:
            if name == "skill":
                # A verified program from Yorika's skill library (backend/programs.py).
                from backend.programs import call
                result = call(argument)
            else:
                result = calc(argument) if name == "calc" else now_text(moment) if name == "time" else memory(argument, directory)
        except (ValueError, OSError) as error:
            result = "(%s)" % error
        calls.append({"tool": name, "input": argument, "result": result})
        return result
    return CALL.sub(replace, answer), calls


def lessons(count=120, seed=7):
    """Synthetic arithmetic, clock and memory lessons in the tool-call format."""
    rng = random.Random(seed)
    words = [("плюс", "+"), ("минус", "-"), ("умножить на", "*"), ("разделить на", "/")]
    topics = ["мою собаку", "мой день рождения", "мою работу", "мои любимые фильмы", "мою семью", "мои планы",
              "мою учёбу", "мои увлечения", "мой город", "мою любимую еду"]
    clock = ["Который час?", "Сколько сейчас времени?", "Какое сегодня число?", "Какой сегодня день недели?",
             "Подскажи дату и время", "Сейчас утро или вечер?"]
    pairs, seen = [], set()
    while len(pairs) < max(count - len(clock) - 2 * len(topics), count * 3 // 4):
        a, b = rng.randint(2, 999), rng.randint(2, 99)
        word, sign = rng.choice(words)
        if sign == "/":
            a = b * rng.randint(2, 50)
        prompt = rng.choice(["Сколько будет %d %s %d?", "Посчитай %d %s %d", "%d %s %d — сколько это?"]) % (a, word, b)
        if prompt in seen:
            continue
        seen.add(prompt)
        pairs.append((prompt, "Считаю: [[calc:%d%s%d]]." % (a, sign, b)))
    pairs += [(q, "Сейчас [[time:]].") for q in clock]
    for topic in topics:
        pairs.append(("Что ты помнишь про %s?" % topic, "Вот что я помню: [[memory:%s]]" % topic.split()[-1]))
        pairs.append(("Напомни, что я говорил про %s" % topic, "Ты говорил: [[memory:%s]]" % topic.split()[-1]))
    return pairs[:count]
